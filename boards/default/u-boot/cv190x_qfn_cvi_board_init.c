int cvi_board_init(void)
{
#if defined(CV190X_QFN_88_PIN)
	PINMUX_CONFIG(XGPIOC15, IIC2_SCL);
	PINMUX_CONFIG(XGPIOC14, IIC2_SDA);
	PINMUX_CONFIG(XGPIOC13, XGPIOC_13);
	PINMUX_CONFIG(XGPIOC12, CAM_MCLK1);
#elif defined(CV190X_QFN_88_PIN_38)
	//I2C2
	PINMUX_CONFIG(XGPIOC15, IIC2_SCL);
	PINMUX_CONFIG(XGPIOC14, IIC2_SDA);
	//CAM_RST0
	PINMUX_CONFIG(PAD_MIPIRX5P, XGPIOC_17);
	PINMUX_CONFIG(PAD_MIPIRX5N, XGPIOC_16);
	//CAM_MCLK0
	PINMUX_CONFIG(XGPIOC13, CAM_MCLK0);
	PINMUX_CONFIG(XGPIOC12, XGPIOC_12);
	//IRCUT
	//PINMUX_CONFIG(SD1_D2, PWR_GPIO19);
	//PINMUX_CONFIG(SD1_D3, PWR_GPIO18);

#elif defined(CV190X_QFN_68_PIN)
	// PINMUX_CONFIG(PAD_MIPIRX1P, IIC1_SDA);
	// PINMUX_CONFIG(PAD_MIPIRX0N, IIC1_SCL);
	// PINMUX_CONFIG(PAD_MIPIRX1N, XGPIOC_8);
	// PINMUX_CONFIG(PAD_MIPIRX0P, CAM_MCLK0);
	//IRCUT
	//PINMUX_CONFIG(SD1_D2, PWR_GPIO19);
	//PINMUX_CONFIG(SD1_D3, PWR_GPIO18);

#endif
	// pinmux for wifi
	pinmux_config(PINMUX_SDIO1);
	PINMUX_CONFIG(PAD_MIPIRX4N, XGPIOC_2);
	PINMUX_CONFIG(PAD_MIPIRX4P, XGPIOC_3);
   PINMUX_CONFIG(XGPIOB25, IIS1_LRCK);
   PINMUX_CONFIG(XGPIOB24, IIS1_DO);
   PINMUX_CONFIG(XGPIOB26, IIS1_DI);
	return 0;
}
